"""Writes THIRD-PARTY.md: every crate the shipped binaries are built from
(normal and build dependencies for Windows x64, no dev-dependencies), its
license, and the license texts the crate ships, read from cargo's local
source copies. Fails if a license isn't on the allowed list.

  python tools/third-party.py          write THIRD-PARTY.md
  python tools/third-party.py --check  fail if it's out of date (CI)
"""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "THIRD-PARTY.md")
# Permissive licenses compatible with distributing Quickseek under MIT OR Apache-2.0.
ALLOWED = {"MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib", "Unicode-3.0", "Unicode-DFS-2016", "BSL-1.0", "CC0-1.0", "Unlicense", "0BSD"}
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE)", re.I)


def ids(expr):
    return set(re.findall(r"[A-Za-z0-9.\-]+", expr.replace("/", " OR "))) - {"OR", "AND", "WITH"}


def ok(expr):
    """At least one choice in an OR is allowed; every part of an AND is."""
    expr = expr.replace("/", " OR ")
    return any(all(i in ALLOWED for i in ids(alt)) for alt in re.split(r"\bOR\b", expr.replace("(", "").replace(")", "")) if alt.strip()) or all(i in ALLOWED for i in ids(expr))


def main():
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc", "--locked"],
                                     cwd=ROOT, capture_output=True, text=True, check=True).stdout)
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    ws = set(meta["workspace_members"])
    seen, stack = set(), list(ws)
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    deps = sorted((pkgs[i] for i in seen - ws), key=lambda p: (p["name"].lower(), p["version"]))
    bad = [f'{p["name"]} {p["version"]}: {p.get("license")}' for p in deps if not p.get("license") or not ok(p["license"])]
    if bad:
        sys.exit("licenses to review:\n  " + "\n  ".join(bad))
    out = ["# Third-party software", "",
           "quickseek's binaries include these crates. Their licenses are all permissive and compatible with",
           "quickseek's own (MIT OR Apache-2.0). Generated by `tools/third-party.py` from `Cargo.lock`.", "",
           "| Crate | Version | License |", "|---|---|---|"]
    out += [f'| [{p["name"]}](https://crates.io/crates/{p["name"]}) | {p["version"]} | {p["license"]} |' for p in deps]
    out += ["", "## License texts", "", "As shipped by each crate; a text that's word for word the same as one above is referred to.", ""]
    norm = lambda t: " ".join(t.split())
    apache = norm(open(os.path.join(ROOT, "LICENSE-APACHE"), encoding="utf-8").read())
    first = {}
    for p in deps:
        d = os.path.dirname(p["manifest_path"])
        files = sorted(f for f in os.listdir(d) if LICENSE_FILE.match(f) and os.path.isfile(os.path.join(d, f)))
        out.append(f'### {p["name"]} {p["version"]}')
        out.append("")
        if not files:
            out += [f'License: {p["license"]} (the crate ships no license file; see its repository: {p.get("repository") or "n/a"}).', ""]
        for f in files:
            text = open(os.path.join(d, f), encoding="utf-8", errors="replace").read().strip()
            key = norm(text)
            if key == apache:
                out += [f"{f}: the Apache License 2.0, word for word as in [LICENSE-APACHE](LICENSE-APACHE).", ""]
                continue
            if key in first:
                out += [f"{f}: the same text as {first[key]}.", ""]
                continue
            first[key] = f'{p["name"]} {p["version"]} ({f})'
            out += [f"<details><summary>{f}</summary>", "", "```text", text.replace("```", "'''"), "```", "", "</details>", ""]
    text = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit("THIRD-PARTY.md is out of date: run python tools/third-party.py")
        print(f"THIRD-PARTY.md is current ({len(deps)} crates)")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}: {len(deps)} crates, {len(text) // 1024} KB")


if __name__ == "__main__":
    main()
